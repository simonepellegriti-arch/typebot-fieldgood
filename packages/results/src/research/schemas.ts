import type { BubbleBlockType } from "@typebot.io/blocks-bubbles/constants";
import type { InputBlockType } from "@typebot.io/blocks-inputs/constants";
import type { VariableDataType } from "@typebot.io/variables/schemas";
import { z } from "zod";
import type {
  AnswerOtherTexts,
  AnswerResearchValue,
  AnswerValueLabel,
} from "../schemas/answers";

export const interviewStatuses = [
  "NOT_STARTED",
  "STARTED",
  "ABANDONED",
  "COMPLETE",
] as const;
export type InterviewStatus = (typeof interviewStatuses)[number];

export const systemColumns = {
  resultId: "RESULT_ID",
  status: "STATUS",
  isStarted: "IS_STARTED",
  isCompleted: "IS_COMPLETED",
  startTs: "START_TS",
  endTs: "END_TS",
  lastActivityTs: "LAST_ACTIVITY_TS",
  durationSeconds: "DURATION_SECONDS",
  typebotVersion: "TYPEBOT_VERSION",
  typebotVersionId: "TYPEBOT_VERSION_ID",
} as const;

export const defaultAbandonedAfterMinutes = 24 * 60;

export const researchExportOptionsSchema = z.object({
  valueMode: z.enum(["value", "label", "both"]).default("value"),
  multipleChoiceMode: z.enum(["compact", "dichotomous"]).default("compact"),
  multipleChoiceSeparator: z
    .string()
    .min(1)
    .max(3)
    .refine((separator) => !/[\r\n"]/.test(separator), {
      message: "Separator can't contain quotes or line breaks",
    })
    .default("|"),
  repeatedAnswersMode: z.enum(["columns", "json", "last"]).default("columns"),
  statusFilter: z.enum(["all", "complete", "incomplete"]).default("all"),
  /** Only export interviews generated by these questionnaire versions. Undefined = all versions. */
  versionNumbers: z.array(z.number().int().positive()).optional(),
  /** With a version filter, also export interviews started before versioning existed. */
  includePreVersioningResults: z.boolean().default(false),
  /** Include results where the respondent opened the bot but never answered. */
  includeNotStarted: z.boolean().default(false),
  abandonedAfterMinutes: z
    .number()
    .int()
    .positive()
    .default(defaultAbandonedAfterMinutes),
  timeZone: z.string().optional(),
  csvMode: z.enum(["excelSafe", "raw"]).default("excelSafe"),
  /** csv: CSV + JSON codebook. sav: SPSS system file with labels, value labels, missing values and MR sets. */
  fileFormat: z.enum(["csv", "sav"]).default("csv"),
  /** Wide columns of loop questions: D2_NIKE (item code) or D2_1 (iteration number). */
  loopColumnNaming: z.enum(["item", "iteration"]).default("item"),
  /** Also produce the long format (one row per answer: RESULT_ID | LOOP | ITEM | QUESTION | VALUE...). */
  includeLongFormat: z.boolean().default(false),
  /** Adds <VAR>_SCORE columns for questions with scored options. */
  includeScores: z.boolean().default(true),
});
export type ResearchExportOptionsInput = z.input<
  typeof researchExportOptionsSchema
>;
export type ResearchExportOptions = z.output<
  typeof researchExportOptionsSchema
>;

export type QuestionOption = {
  value: string | number;
  label: string;
};

export const videoMetrics = [
  "STARTED",
  "COMPLETED",
  "WATCHED_SECONDS",
  "WATCHED_PCT",
  "PAUSES",
] as const;
export type VideoMetric = (typeof videoMetrics)[number];

export type DictionaryQuestion = {
  /** Stable technical id (the block id). Never derived from visible texts. */
  id: string;
  blockId: string;
  blockType: InputBlockType | BubbleBlockType.VIDEO;
  /** standard: one value per answer. matrix: one value per row. video: watch metrics. */
  kind: "standard" | "matrix" | "video";
  variableId?: string;
  /** Column base name. Comes from the variable name, never from labels. */
  variableName: string;
  /** Question text / variable label. Changing it never changes the column name. */
  label: string;
  dataType: VariableDataType;
  isMultiple: boolean;
  options: QuestionOption[];
  missingValues: (string | number)[];
  versionNumbers: number[];
  /** Matrix rows (codes + labels) in builder order. Options are the matrix columns. */
  matrixRows?: QuestionOption[];
  isMultiplePerRow?: boolean;
  /** Codes of "Other, please specify" options (open text exported in its own column). */
  otherOptionValues?: (string | number)[];
  /** At least one option / matrix column has a score. */
  hasScores?: boolean;
};

export type DatasetDictionary = {
  questions: DictionaryQuestion[];
  /** Result variables that are not linked to an input block (hidden fields, computed vars...) */
  variables: {
    id: string;
    name: string;
    label: string;
    dataType: VariableDataType;
    missingValues: (string | number)[];
  }[];
  /** Loop blocks: name used in exports and labels of their items (by item code). */
  loops?: {
    blockId: string;
    name: string;
    itemLabels: Record<string, string>;
  }[];
};

export type NormalizedAnswer = {
  blockId: string;
  executionIndex: number;
  createdAt?: Date;
  value: AnswerResearchValue | null;
  valueLabel: AnswerValueLabel | null;
  otherTexts: AnswerOtherTexts | null;
  score: number | null;
  rowScores: Record<string, number | null> | null;
  loopBlockId: string | null;
  loopIteration: number | null;
  loopItem: string | null;
  content: string;
};

export type DatasetCell = string | number | boolean | null;

export type DatasetColumn = {
  name: string;
  kind: "system" | "question" | "variable";
  questionId?: string;
  /** For dichotomous columns: the option value represented by the column. */
  optionValue?: string | number;
  /** For repeated answers: 1-based execution index represented by the column. */
  executionIndex?: number;
  /** Matrix: code of the row represented by the column. */
  matrixRowValue?: string | number;
  /** Loop iteration represented by the column (wide export of loop questions). */
  loopSlot?: { loopBlockId: string; loopItem?: string; loopIteration?: number };
  /** Score column: of the whole answer, or of one matrix row. */
  scoreOf?: { matrixRowValue?: string | number };
  /** Tracked video: metric represented by the column. */
  videoMetric?: VideoMetric;
  /**
   * "Other, please specify" open text column. `optionValue` is set for multiple choice
   * (one text column per option); unset for single choice (text of the selected option).
   */
  otherText?: { optionValue?: string | number };
  isLabelColumn?: boolean;
  label: string;
  type: "numeric" | "string" | "datetime";
};

export type ResearchDataset = {
  columns: DatasetColumn[];
  rows: DatasetCell[][];
};
